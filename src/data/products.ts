export const getProduct = (slug: string) => products.find((p) => p.slug === slug);
export const productsInCategory = (slug: string) => products.filter((p) => p.category === slug);
export const featuredProducts = () => products.filter((p) => p.featured);
export const relatedProducts = (p: Product, n = 4) =>
  products.filter((x) => x.category === p.category && x.slug !== p.slug).concat(
    products.filter((x) => x.category !== p.category && x.featured),
  ).slice(0, n);
export const brands = () => Array.from(new Set(products.map((p) => p.brand).filter(Boolean) as string[])).sort();
